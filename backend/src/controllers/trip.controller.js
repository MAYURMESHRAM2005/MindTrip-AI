/**
 * Self-heal stored validation: re-run the deterministic Final Validator
 * against the itinerary's current days before serving it. Validation issues
 * are persisted at generation time, so trips generated by an older validator
 * build would otherwise show stale warnings (e.g. false "overlaps")
 * forever. The deterministic checks are pure and cheap - recompute them on
 * read and persist only when the result actually changed.
 */
async function refreshValidation(itinerary, trip) {
  if (!itinerary || !trip) return;
  const fresh = finalValidatorAgent.runDeterministic({
    days: itinerary.days,
    budget: trip.budget?.total ?? 0,
    totalEstimatedCost: itinerary.totalEstimatedCost ?? trip.totalEstimatedCost ?? 0,
    destination: trip.destination,
    origin: trip.origin || '',
    prefs: trip.preferences || {},
  });
  const old = itinerary.validation || {};
  const changed =
    old.passed !== fresh.passed ||
    JSON.stringify(old.issues || []) !== JSON.stringify(fresh.issues) ||
    JSON.stringify(old.warnings || []) !== JSON.stringify(fresh.warnings);
  if (changed) {
    itinerary.set('validation', {
      passed: fresh.passed,
      issues: fresh.issues,
      warnings: fresh.warnings,
      validatedAt: new Date(),
    });
    try {
      await itinerary.save();
    } catch {
      // Non-fatal: a persistence failure must not block serving the trip.
    }
  }
}

export const generate = asyncHandler(async (req, res) => {
  logger.entry('[CTRL:trip]', 'generate', { userId: req.user._id, destination: req.body.destination, origin: req.body.origin, startDate: req.body.startDate, endDate: req.body.endDate, totalBudget: req.body.totalBudget });
  const request = { ...req.body, title: sanitizeText(req.body.title, 160) || undefined };
  const result = await orchestrator.generateTrip({ user: req.user, request });
  logger.exit('[CTRL:trip]', 'generate', { status: 'success', tripId: result.trip?._id, pipelineMs: result.pipelineMs });
  res.status(201).json(
    ApiResponse.created('Trip generated by multi-agent pipeline', result)
  );
});

export const listTrips = asyncHandler(async (req, res) => {
  logger.debug(`[CTRL:trip] listTrips for user: ${req.user._id}`);
  const trips = await Trip.find({ user: req.user._id }).sort({ createdAt: -1 }).limit(50);
  logger.debug(`[CTRL:trip] listTrips returned ${trips.length} trips`);
  res.json(ApiResponse.ok('Trips', { trips }));
});

export const getTrip = asyncHandler(async (req, res) => {
  logger.debug(`[CTRL:trip] getTrip: ${req.params.id} for user: ${req.user._id}`);
  const trip = await Trip.findOne({ _id: req.params.id, user: req.user._id });
  if (!trip) {
    logger.warn(`[CTRL:trip] Trip not found: ${req.params.id}`);
    throw ApiError.notFound('Trip not found');
  }
  const itinerary = await Itinerary.findOne({ trip: trip._id });
  await refreshValidation(itinerary, trip);
  res.json(ApiResponse.ok('Trip', { trip, itinerary }));
});

