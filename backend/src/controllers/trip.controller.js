export const generate = asyncHandler(async (req, res) => {
  const request = { ...req.body, title: sanitizeText(req.body.title, 160) || undefined };
  const result = await orchestrator.generateTrip({ user: req.user, request });
  res.status(201).json(
    ApiResponse.created('Trip generated by multi-agent pipeline', result)
  );
});

