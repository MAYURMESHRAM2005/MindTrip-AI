import crypto from 'crypto';
import ApiResponse from '../utils/ApiResponse.js';
import asyncHandler from '../utils/asyncHandler.js';
import Ticket from '../models/Ticket.js';

export const listTickets = asyncHandler(async (req, res) => {
  const filter = { user: req.user._id };
  if (req.query.tripId) filter.trip = req.query.tripId;
  const tickets = await Ticket.find(filter).sort({ createdAt: -1 }).limit(100);
  res.json(ApiResponse.ok('Tickets', { tickets }));
});

/**
 * Create a ticket. A QR code is generated ONLY from:
 *  - a reference the user provides (their own booking), or
 *  - an application-generated reference (clearly marked isFabricated=false
 *    but generated by the app, never claiming to be an airline/train booking).
 */
export const addTicket = asyncHandler(async (req, res) => {
  const { reference, ...rest } = req.body;
  let ref = reference || `TM-${crypto.randomBytes(4).toString('hex').toUpperCase()}`;
  const ticket = await Ticket.create({
    ...rest,
    user: req.user._id,
    reference: ref,
    qrData: ref,
    qrGenerated: true,
    isFabricated: !reference,
  });
  res.status(201).json(ApiResponse.created('Ticket stored with QR reference', { ticket }));
});

export const deleteTicket = asyncHandler(async (req, res) => {
  await Ticket.findOneAndDelete({ _id: req.params.id, user: req.user._id });
  res.json(ApiResponse.ok('Ticket deleted'));
});

export const regenerateQr = asyncHandler(async (req, res) => {
  const ticket = await Ticket.findOne({ _id: req.params.id, user: req.user._id });
  if (!ticket) return res.status(404).json({ success: false, message: 'Ticket not found' });
  ticket.qrData = ticket.reference;
  ticket.qrGenerated = true;
  await ticket.save();
  res.json(ApiResponse.ok('QR refreshed from stored reference', { ticket }));
});

export default { listTickets, addTicket, deleteTicket, regenerateQr };
